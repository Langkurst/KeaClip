"""Golden vectors for KeaClip watch links (seekable RFC 8188 aes128gcm).

An independent implementation (Python `cryptography`) used to freeze vectors.json. The .NET encryptor must reproduce
every ciphertext byte for byte (tests/Klippi.Tests/WatchLinkTests.cs) and the browser decryptor must decrypt every
vector and reject tampered ones (web/watch/test/ece.test.mjs). Run from this folder: python -I make-vectors.py
"""
import base64, hashlib, json, os, struct
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.hkdf import HKDF
from cryptography.hazmat.primitives import hashes


def b64u(b): return base64.urlsafe_b64encode(b).rstrip(b"=").decode()
def unb64u(s): return base64.urlsafe_b64decode(s + "=" * (-len(s) % 4))


def hkdf(secret, salt, info, length):
    return HKDF(algorithm=hashes.SHA256(), length=length, salt=salt, info=info).derive(secret)


def keys(secret, salt):
    return hkdf(secret, salt, b"Content-Encoding: aes128gcm\x00", 16), hkdf(secret, salt, b"Content-Encoding: nonce\x00", 12)


def nonce(base, seq):
    value, = struct.unpack(">Q", base[4:])
    return base[:4] + struct.pack(">Q", value ^ seq)


def encrypt(secret, salt, rs, plain):
    key, base = keys(secret, salt)
    aes = AESGCM(key)
    payload = rs - 17
    records = max(1, -(-len(plain) // payload))
    out = salt + struct.pack(">I", rs) + b"\x00"
    for i in range(records):
        chunk = plain[i * payload:(i + 1) * payload]
        out += aes.encrypt(nonce(base, i), chunk + (b"\x02" if i == records - 1 else b"\x01"), None)
    return out


def decrypt(secret, data):
    salt, rs, idlen = data[:16], struct.unpack(">I", data[16:20])[0], data[20]
    key, base = keys(secret, salt)
    aes = AESGCM(key)
    pos, i, out = 21 + idlen, 0, b""
    while pos < len(data):
        rec = aes.decrypt(nonce(base, i), data[pos:pos + rs], None).rstrip(b"\x00")
        final = pos + rs >= len(data)
        assert rec[-1] == (2 if final else 1)
        out += rec[:-1]
        pos += rs
        i += 1
    return out


def pattern(n): return bytes((i * 7 + 3) % 251 for i in range(n))


# RFC 8188 section 3.1 (published example): one record, rs 4096.
RFC_KEY, RFC_CIPHER = "yqdlZ-tYemfogSmv7Ws5PQ", "I1BsxtFttlv3u_Oo94xnmwAAEAAA-NAVub2qFgBEuQKRapoZu-IxkIva3MEB1PD-ly8Thjg"
assert decrypt(unb64u(RFC_KEY), unb64u(RFC_CIPHER)) == b"I am the walrus"
assert encrypt(unb64u(RFC_KEY), unb64u(RFC_CIPHER)[:16], 4096, b"I am the walrus") == unb64u(RFC_CIPHER)

KEY = bytes(range(16))
vectors = [{"name": "rfc8188-3.1", "source": "RFC 8188 section 3.1", "key": RFC_KEY, "rs": 4096, "saltHex": unb64u(RFC_CIPHER)[:16].hex(),
            "plaintextLength": 15, "plaintext": b"I am the walrus".hex(), "plaintextSha256": hashlib.sha256(b"I am the walrus").hexdigest(),
            "ciphertextSha256": hashlib.sha256(unb64u(RFC_CIPHER)).hexdigest(), "ciphertext": RFC_CIPHER}]
for name, rs, plain, salt in [
    ("multi-record", 64, pattern(300), bytes(range(0xA0, 0xB0))),
    ("exact-boundary", 64, pattern(94), bytes(range(0xB0, 0xC0))),
    ("empty", 64, b"", bytes(range(0xC0, 0xD0))),
    ("utf8-default-record-size", 65536, "KeaClip watch link ✓ Aotearoa".encode(), bytes(range(0xD0, 0xE0))),
    ("three-default-records", 65536, pattern(65519 * 2 + 1000), bytes(range(0xE0, 0xF0))),
]:
    cipher = encrypt(KEY, salt, rs, plain)
    assert decrypt(KEY, cipher) == plain
    entry = {"name": name, "key": b64u(KEY), "rs": rs, "saltHex": salt.hex(), "plaintextLength": len(plain),
             "plaintext": "pattern" if len(plain) > 0 and plain == pattern(len(plain)) else plain.hex(),
             "plaintextSha256": hashlib.sha256(plain).hexdigest(), "ciphertextSha256": hashlib.sha256(cipher).hexdigest()}
    if len(cipher) <= 4096:
        entry["ciphertext"] = b64u(cipher)
    vectors.append(entry)

with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "vectors.json"), "w", newline="\n") as out:
    json.dump({"comment": "Generated by make-vectors.py (Python cryptography). 'pattern' means byte i = (7*i + 3) mod 251. Large vectors list only hashes.",
               "vectors": vectors}, out, indent=2)
    out.write("\n")
print("wrote", len(vectors), "vectors")
